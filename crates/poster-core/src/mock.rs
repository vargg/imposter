//! Static local mock responses. Configuration is independent of request collections.

use serde::{Deserialize, Serialize};

use crate::model::{ParamItem, is_method_token};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct MockConfig {
    pub port: u16,
    pub routes: Vec<MockRoute>,
}

impl Default for MockConfig {
    fn default() -> Self {
        Self {
            port: 8080,
            routes: Vec::new(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct MockRoute {
    pub enabled: bool,
    pub method: String,
    pub path: String,
    pub status: u16,
    pub headers: Vec<ParamItem>,
    pub body: String,
}

impl Default for MockRoute {
    fn default() -> Self {
        Self {
            enabled: true,
            method: "GET".into(),
            path: "/".into(),
            status: 200,
            headers: Vec::new(),
            body: String::new(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("Route {route}: {reason}")]
pub struct MockConfigError {
    pub route: usize,
    pub reason: &'static str,
}

impl MockConfig {
    pub fn validate(&self) -> Result<(), MockConfigError> {
        let mut keys = std::collections::BTreeSet::new();
        for (index, route) in self.routes.iter().enumerate() {
            let error = |reason| MockConfigError {
                route: index + 1,
                reason,
            };
            if !is_method_token(&route.method) {
                return Err(error("method must be an HTTP token"));
            }
            if !route.path.starts_with('/')
                || route
                    .path
                    .bytes()
                    .any(|b| !b.is_ascii() || b <= b' ' || b == 127 || b == b'?' || b == b'#')
            {
                return Err(error(
                    "use an encoded path beginning with /, without a query or fragment",
                ));
            }
            if !(200..=599).contains(&route.status) {
                return Err(error("response status must be between 200 and 599"));
            }
            for header in route.headers.iter().filter(|header| header.is_enabled) {
                if !is_method_token(&header.name)
                    || header
                        .value
                        .bytes()
                        .any(|b| (b < 32 && b != b'\t') || b == 127)
                {
                    return Err(error("header name or value is invalid"));
                }
                if [
                    "content-length",
                    "transfer-encoding",
                    "connection",
                    "trailer",
                    "upgrade",
                ]
                .iter()
                .any(|name| header.name.eq_ignore_ascii_case(name))
                {
                    return Err(error(
                        "response framing headers are generated by the server",
                    ));
                }
            }
            if route.enabled && !keys.insert((&route.method, &route.path)) {
                return Err(error("an enabled route already has this method and path"));
            }
        }
        Ok(())
    }

    pub fn matching_route(&self, method: &str, path: &str) -> Option<&MockRoute> {
        self.routes
            .iter()
            .find(|route| route.enabled && route.method == method && route.path == path)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn invalid_rules_and_duplicate_enabled_keys_are_rejected() {
        let route = MockRoute::default();
        let config = |route| MockConfig {
            routes: vec![route],
            ..Default::default()
        };
        config(route.clone()).validate().unwrap();
        for method in ["", "GET POST", "G\nET"] {
            assert!(
                config(MockRoute {
                    method: method.into(),
                    ..route.clone()
                })
                .validate()
                .is_err()
            );
        }
        for path in ["", "relative", "/a?b", "/a#b", "/a b", "/é", "/\r"] {
            assert!(
                config(MockRoute {
                    path: path.into(),
                    ..route.clone()
                })
                .validate()
                .is_err()
            );
        }
        for status in [0, 101, 199, 600] {
            assert!(
                config(MockRoute {
                    status,
                    ..route.clone()
                })
                .validate()
                .is_err()
            );
        }
        for (name, value) in [
            ("bad name", "x"),
            ("X", "x\r\ny"),
            ("Content-Length", "1"),
            ("Transfer-Encoding", "chunked"),
            ("Connection", "close"),
            ("Trailer", "X"),
            ("Upgrade", "websocket"),
        ] {
            assert!(
                config(MockRoute {
                    headers: vec![ParamItem::new(name, value)],
                    ..route.clone()
                })
                .validate()
                .is_err()
            );
        }
        let mut config = MockConfig {
            routes: vec![route.clone(), route],
            ..Default::default()
        };
        assert!(config.validate().is_err());
        config.routes[1].enabled = false;
        config.validate().unwrap();
        assert!(config.matching_route("GET", "/").is_some());
        assert!(config.matching_route("POST", "/").is_none());
        assert!(config.matching_route("GET", "/other").is_none());
    }
}
